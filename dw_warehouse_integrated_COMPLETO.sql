USE dw_warehouse_integrated;

-- Crear (o reemplazar) la vista que simula el cubo de ventas
CREATE OR REPLACE VIEW vw_cubo_ventas AS
SELECT
    t.Mes                 AS Mes,
    p.Subcategoria        AS Subcategoria,
    s.Region              AS Region,
    s.Departamento        AS Departamento,
    s.Ciudad              AS Ciudad,
    SUM(h.Cantidad)       AS CantidadVendida,
    SUM(h.TotalVenta)     AS TotalVenta,
    SUM(h.CostoUnitario)  AS CostoUnitario,
    SUM(h.MargenTotal)    AS MargenTotal
FROM hecho_ventas h
    INNER JOIN dim_tiempo   t ON h.IdTiempo   = t.IdTiempo
    INNER JOIN dim_producto p ON h.IdProducto = p.IdProducto
    INNER JOIN dim_tienda   s ON h.IdTienda   = s.IdTienda
GROUP BY t.Mes, p.Subcategoria, s.Region, s.Departamento, s.Ciudad;

-- Consultar el cubo (ordenado para verlo mejor)
SELECT * FROM vw_cubo_ventas
ORDER BY Mes, Region, Ciudad, Subcategoria;
