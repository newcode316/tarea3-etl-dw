-- 1) Crear la base de datos (la bodega de datos)
CREATE DATABASE IF NOT EXISTS dw_warehouse_integrated
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

-- 2) Indicar que vamos a trabajar sobre esa base de datos
USE dw_warehouse_integrated;

-- ------------------------------------------------------------
-- 3) DIMENSION TIEMPO  (fuente: Anexo 10 - Tiempo)
-- ------------------------------------------------------------
CREATE TABLE dim_tiempo (
  IdTiempo     INT PRIMARY KEY,
  Fecha        DATE,
  Dia          INT,
  Mes          INT,
  Trimestre    INT,
  Anio         INT,
  DiaSemana    VARCHAR(15),
  EsFinSemana  TINYINT
);

-- ------------------------------------------------------------
-- 4) DIMENSION PRODUCTO  (fuente: Anexo 9 - Productos)
-- ------------------------------------------------------------
CREATE TABLE dim_producto (
  IdProducto     INT PRIMARY KEY,
  ProductoNombre VARCHAR(100),
  Marca          VARCHAR(50),
  Modelo         VARCHAR(50),
  Categoria      VARCHAR(50),
  Subcategoria   VARCHAR(50),
  Precio         BIGINT
);

-- ------------------------------------------------------------
-- 5) DIMENSION TIENDA  (fuente: Anexo 8 - Tiendas)
-- ------------------------------------------------------------
CREATE TABLE dim_tienda (
  IdTienda     INT PRIMARY KEY,
  Ciudad       VARCHAR(50),
  Departamento VARCHAR(50),
  Region       VARCHAR(50)
);

-- ------------------------------------------------------------
-- 6) DIMENSION CLIENTE  (fuente: Anexo 11 - Clientes)
--    Aqui ingresaran los datos YA LIMPIOS por el proceso ETL.
-- ------------------------------------------------------------
CREATE TABLE dim_cliente (
  IdCliente INT PRIMARY KEY,
  Nombre    VARCHAR(100),
  Email     VARCHAR(100),
  Telefono  VARCHAR(20),
  Segmento  VARCHAR(20),
  Ciudad    VARCHAR(50),
  Sexo      VARCHAR(1),
  Edad      INT
);

-- ------------------------------------------------------------
-- 7) TABLA DE HECHOS: VENTAS  (fuente: Anexo 12 - Ventas)
--    Guarda las metricas y se conecta con las 4 dimensiones.
-- ------------------------------------------------------------
CREATE TABLE hecho_ventas (
  IdVenta        INT PRIMARY KEY,
  IdTiempo       INT,
  IdCliente      INT,
  IdProducto     INT,
  IdTienda       INT,
  Cantidad       INT,
  PrecioUnitario BIGINT,
  TotalVenta     BIGINT,
  CostoUnitario  BIGINT,
  MargenUnitario BIGINT,
  MargenTotal    BIGINT,
  CONSTRAINT fk_ventas_tiempo   FOREIGN KEY (IdTiempo)   REFERENCES dim_tiempo(IdTiempo),
  CONSTRAINT fk_ventas_cliente  FOREIGN KEY (IdCliente)  REFERENCES dim_cliente(IdCliente),
  CONSTRAINT fk_ventas_producto FOREIGN KEY (IdProducto) REFERENCES dim_producto(IdProducto),
  CONSTRAINT fk_ventas_tienda   FOREIGN KEY (IdTienda)   REFERENCES dim_tienda(IdTienda)
);

