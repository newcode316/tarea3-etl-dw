USE dw_warehouse_integrated;

DROP PROCEDURE IF EXISTS sp_etl_clientes;

DELIMITER $$
CREATE PROCEDURE sp_etl_clientes()
BEGIN
    -- Variable para guardar el promedio de edad (imputacion de nulos)
    DECLARE v_promedio_edad INT;

    -- 1) Calcular el promedio de las edades validas (solo numeros)
    SELECT ROUND(AVG(CAST(Edad AS UNSIGNED)))
      INTO v_promedio_edad
      FROM stg_clientes
      WHERE Edad REGEXP '^[0-9]+$';

    -- 2) Vaciar el destino para poder re-ejecutar sin duplicar
    DELETE FROM dim_cliente;

    -- 3) Insertar los datos YA LIMPIOS en dim_cliente
    INSERT INTO dim_cliente (IdCliente, Nombre, Email, Telefono, Segmento, Ciudad, Sexo, Edad)
    SELECT
        CAST(idCliente AS UNSIGNED),
        -- Nombre: quitar espacios; si es nulo/vacio -> 'No registrado'
        CASE WHEN TRIM(IFNULL(Nombre,'')) = '' THEN 'No registrado'
             ELSE TRIM(Nombre) END,
        -- Email: si es nulo/vacio -> 'No registrado'
        CASE WHEN TRIM(IFNULL(Email,'')) = '' THEN 'No registrado'
             ELSE TRIM(Email) END,
        -- Telefono: si es nulo/vacio -> 'No registrado'
        CASE WHEN TRIM(IFNULL(Telefono,'')) = '' THEN 'No registrado'
             ELSE TRIM(Telefono) END,
        -- Segmento: quitar espacios
        TRIM(IFNULL(Segmento,'')),
        -- Ciudad: MAYUSCULAS, sin espacios y sin tildes; nulo -> 'NO ESPECIFICADA'
        CASE WHEN TRIM(IFNULL(Ciudad,'')) = '' THEN 'NO ESPECIFICADA'
             ELSE REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(
                    UPPER(TRIM(Ciudad)),'Á','A'),'É','E'),'Í','I'),'Ó','O'),'Ú','U')
        END,
        -- Sexo: quitar espacios (queda 'M' o 'F'); si es nulo -> NULL
        CASE WHEN TRIM(IFNULL(Sexo,'')) = '' THEN NULL
             ELSE TRIM(Sexo) END,
        -- Edad: si es un numero valido se conserva; si no, se usa el promedio
        CASE WHEN Edad REGEXP '^[0-9]+$' THEN CAST(Edad AS UNSIGNED)
             ELSE v_promedio_edad END
    FROM stg_clientes;
END$$
DELIMITER ;


